//! Embed the schedule SPA (`ui/dist`) into the binary.
//!
//! The UI is built by Bun (`./build ui`) and the output is committed, so the
//! Nix build stays hermetic — there is no Bun, node or network in the firmware
//! derivation, and the image stays bit-reproducible (AGENTS.md trap 23). This
//! script only copies the three asset files into `OUT_DIR` and generates the
//! `include_bytes!` shim; a missing `ui/dist` is not an error, it just makes
//! `/` serve a "UI not built" page so `cargo build` never depends on Bun.

use std::env;
use std::fs;
use std::path::PathBuf;

/// (Rust identifier, file in ui/dist, Content-Type).
const ASSETS: &[(&str, &str, &str)] = &[
    ("INDEX_HTML", "index.html", "text/html; charset=utf-8"),
    ("APP_JS", "index.js", "text/javascript; charset=utf-8"),
    ("APP_CSS", "app.css", "text/css; charset=utf-8"),
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let dist = manifest.join("ui").join("dist");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=ui/dist");

    let mut shim =
        String::from("// Generated by build.rs — do not edit.\nuse super::Asset;\n");
    let mut present = true;

    for (ident, file, content_type) in ASSETS {
        let blob = out_dir.join(format!("{file}.bin"));
        match fs::read(dist.join(file)) {
            Ok(bytes) => fs::write(&blob, bytes).expect("write asset blob"),
            Err(_) => {
                present = false;
                fs::write(&blob, b"").expect("write empty asset blob");
            }
        }
        shim.push_str(&format!(
            "pub static {ident}: Asset = Asset {{ body: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}.bin\")), content_type: \"{content_type}\" }};\n"
        ));
    }

    shim.push_str(&format!("pub const PRESENT: bool = {present};\n"));
    fs::write(out_dir.join("ui_assets.rs"), shim).expect("write ui_assets.rs");
}
